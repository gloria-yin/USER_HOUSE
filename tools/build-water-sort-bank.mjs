import { writeFile } from 'node:fs/promises';
import { generateWaterSortCandidate, waterSortRandom, waterSortStructureKey } from '../src/games/water-sort-puzzles.js';
import { verifyWaterSortSolution } from '../src/games/water-sort.js';

const bank = [];
const seen = new Set();
for (let tier = 1; tier <= 40; tier++) {
  const level = tier * 3;
  // Preserve the existing bank's seeds and full-shuffle difficulty.
  const random = waterSortRandom(0x7b29e419 + (level - 2) * 104729);
  const puzzles = [];
  for (let batch = 0; puzzles.length < 10 && batch < 200; batch++) {
    const puzzle = generateWaterSortCandidate(level, random, {
      attempts:128, maxNodes:16000, maxTimeMs:Infinity, excluded:[...seen],
    });
    if (!puzzle) continue;
    if (!verifyWaterSortSolution(puzzle.bottles, puzzle.solution, puzzle.colorCount)) {
      throw new Error('Invalid solution at level ' + level);
    }
    seen.add(waterSortStructureKey(puzzle.bottles));
    puzzles.push(puzzle);
  }
  if (puzzles.length !== 10) throw new Error('Not enough distinct puzzles at level ' + level);
  bank.push(puzzles);
  console.log('Verified tier ' + tier + '/40');
}
const source = '// Generated by tools/build-water-sort-bank.mjs. Every reference path is replay-tested separately.\n'
  + 'export const WATER_SORT_BANK = ' + JSON.stringify(bank) + ';\n';
await writeFile(new URL('../src/games/water-sort-bank.js', import.meta.url), source);
console.log('Wrote ' + seen.size + ' distinct verified puzzles');
