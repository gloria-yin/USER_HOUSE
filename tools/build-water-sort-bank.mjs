import { writeFileSync } from 'node:fs';
import { generateWaterSortCandidate, waterSortRandom, waterSortStructureKey } from '../src/games/water-sort-puzzles.js';

const bank = [];
for (let tier = 1; tier <= 40; tier++) {
  const variants = [];
  for (const hardRound of [false, true]) {
    const puzzles = [];
    const seen = new Set();
    const level = tier * 3 - (hardRound ? 0 : 2);
    for (let seed = 1; seed <= 400 && puzzles.length < 5; seed++) {
      const candidate = generateWaterSortCandidate(level, waterSortRandom((tier * 2 + Number(hardRound)) * 100000 + seed), { attempts:24, maxNodes:15000 });
      if (!candidate) continue;
      const signature = waterSortStructureKey(candidate.bottles);
      if (seen.has(signature)) continue;
      seen.add(signature);
      puzzles.push(candidate);
    }
    if (puzzles.length < 5) throw new Error('Insufficient verified puzzles for tier ' + tier + (hardRound ? ' hard' : ' normal'));
    variants.push(puzzles);
    console.log('Tier', tier, hardRound ? 'hard' : 'normal', 'verified', puzzles.map(p => p.complexity + '/' + p.par).join(' '));
  }
  bank.push(variants);
}
writeFileSync(new URL('../src/games/water-sort-bank.js', import.meta.url),
  '// Generated by tools/build-water-sort-bank.mjs. Every reference path is replay-tested separately.\nexport const WATER_SORT_BANK = ' + JSON.stringify(bank) + ';\n');
