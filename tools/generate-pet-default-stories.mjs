const relationshipMomentUsage = new Map();

function relationshipMoment(pet, id, event, stage) {
  if (id === 'M06' && stage === 'juvenile') {
    const index = seededIndex(`${pet.key}:${id}:first-outing`) % juvenileFirstOutings.length;
    return juvenileFirstOutings[index](pet);
  }

  if (id === 'M11') {
    const index = seededIndex(`${pet.key}:${id}:growth-choice`) % growthChoiceMoments.length;
    return growthChoiceMoments[index](pet);
  }

  const context = `${event.title || ''}${event.summary || ''}${event.scene || ''}`;
  const contextKey = /(洗澡|清洗|洗净|洗爪|擦洗|冲洗|泡沫|澡堂|洗护|吹干|擦干|梳洗|清洁(?:毛发|皮毛|羽毛|爪))/.test(context)
    ? 'wet'
    : /(奔跑|开跑|追逐|追赶|散步|巡回|巡逻|出门|外出|屋顶|飞行|航线|返航|山坡|街巷|巷口|门外|河岸|小径|车站|月台|路口|转角)/.test(context)
      ? 'motion'
      : 'quiet';
  const options = relationshipMoments[stage]?.[contextKey] || relationshipMoments[stage]?.quiet;
  if (!options?.length) return '';
  const usageKey = `${pet.key}:${stage}:${contextKey}`;
  const usageCount = relationshipMomentUsage.get(usageKey) || 0;
  const startIndex = seededIndex(usageKey) % options.length;
  const index = (startIndex + usageCount) % options.length;
  relationshipMomentUsage.set(usageKey, usageCount + 1);
  return options[index](pet);
}

