function yamlQuotes(values, spaces) {
  if (!values.length) return '[]';
  return `\n${values.map(value => `${' '.repeat(spaces)}- "${q(value)}"`).join('\n')}`;
}

function renderPet(pet) {
  const arc = storyArcs[pet.key];
  if (!arc) throw new Error(`Missing default story arc for ${pet.key}`);
  const mains = [];
  for (let n = 1; n <= 13; n++) {
    const id = `M${String(n).padStart(2, '0')}`;
    const event = arc.main[id];
    if (!event) throw new Error(`Missing ${id} in ${pet.key} story arc`);
    const branch = n === 12 ? 'spirit' : n === 13 ? 'ordinary' : 'common';
    mains.push(`  - id: ${id}\n    branch: ${branch}\n    title: ${event.title}\n    summary: ${event.summary}\n    story: |-\n${ind(story(pet, id, event, branch), 6)}`);
  }
  for (const id of ['M14','M15']) {
    const spirit = arc.endings.spirit[id];
    const ordinary = arc.endings.ordinary[id];
    if (!spirit || !ordinary) throw new Error(`Missing ${id} ending variants in ${pet.key} story arc`);
    const extraSpirit = id === 'M15' ? `\n        pet_state: returned\n        left_item: ${pet.item}` : '';
    const extraOrdinary = id === 'M15' ? `\n        pet_state: returned\n        left_item: ${pet.trace}` : '';
    mains.push(`  - id: ${id}\n    branch: variant\n    variants:\n      spirit:\n        title: ${spirit.title}\n        summary: ${spirit.summary}${extraSpirit}\n        story: |-\n${ind(story(pet, id, spirit, 'spirit'), 10)}\n      ordinary:\n        title: ${ordinary.title}\n        summary: ${ordinary.summary}${extraOrdinary}\n        story: |-\n${ind(story(pet, id, ordinary, 'ordinary'), 10)}`);
  }

  const sides = pet.sides.map(row => sideEvent(pet, row)).map(side => `  - id: ${side.id}\n    trigger:\n      stage: ${side.stage}\n      context_type: ${side.contextType}\n      context_value: ${side.contextValue}\n      behavior_trigger_type: ${side.triggerType}\n      behavior: ${side.behavior}\n      threshold: ${side.threshold ?? 'null'}\n      probability: ${side.probability ?? 'null'}\n    repeatable: false\n    title: ${side.title}\n    opening_cause: ${side.cause}\n    story: |-\n${ind(story(pet, side.id, side.event, 'common', side.stage), 6)}`).join('\n\n');
  const quotes = quoteBlock(pet);
  const charStages = ['egg','juvenile','adult','spirit'].map(stage => {
    const actions = ['feed','pet','poke'];
    return `    ${stage}:\n` + actions.map(action => `      ${action}:${yamlQuotes(quotes.char[stage][action], 8)}`).join('\n');
  }).join('\n');
  const petStages = ['juvenile','adult','spirit'].map(stage => {
    const actions = ['feed','pet','poke','sleep','sad'];
    return `    ${stage}:\n` + actions.map(action => `      ${action}:${yamlQuotes(quotes.pet[stage][action], 8)}`).join('\n');
  }).join('\n');

  return neutralizeDefaultEggText(`<pet_info>\npet_card:\n  pet_name: ${pet.name}\n  sex: ${pet.sex}\n  spirit_tendency_skill: ${pet.skill}\n  species: ${pet.species}\n  personality: ${pet.personality}\n  adoption_cycle: 1\n\nmain_story:\n${mains.join('\n\n')}\n\nside_story:\n${sides}\n\nquotes:\n  char:\n${charStages}\n  pet:\n${petStages}\n</pet_info>\n`);
}

await mkdir(outDir, { recursive:true });
for (const pet of pets) {
  const rendered = renderPet(pet);
  if (/\$\{pet\./.test(rendered)) throw new Error(`Unresolved pet placeholder in ${pet.key}`);
  await writeFile(resolve(outDir, `pet_info_${pet.key}.txt`), rendered, 'utf8');
}

