function relationshipStage(id, stageOverride) {
  if (stageOverride === 'juvenile' || id.startsWith('SJ')) return 'juvenile';
  if (stageOverride === 'adult' || id.startsWith('SA')) return 'adult';
  const n = Number(id.replace(/\D/g, '')) || 1;
  if (n <= 4) return 'egg';
  if (n <= 8) return 'juvenile';
  if (n <= 13) return 'adult';
  return 'ending';
}

