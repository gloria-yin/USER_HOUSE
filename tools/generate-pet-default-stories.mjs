function sideStoryScene(pet, row, cause) {
  const [id, stage, contextType, contextValue] = row;
  const profile = petActionProfiles[pet.key];
  const setting = contextType === 'time' && contextValue === 'night'
    ? '夜灯刚在窗上落稳，店里最后一点白日的嘈杂也静了下来。'
    : contextValue === 'outside'
      ? '街角的风掠过招牌，你刚跨出店门，牵引绳便在掌心轻轻一动。'
      : contextValue === 'garden'
        ? '花园木门吱呀一声弹回去，潮湿草叶的气味顺着台阶漫上来。'
        : '午后的光斜过柜台，沈栖白刚把手边最后一件东西放回原位。';
  const incident = neutralizeDefaultEggText(cause)
    .split(/[，。！？]/)[0]
    .replace(/[。！？]+$/g, '')
    .trim();
  const index = seededIndex(`${pet.key}:${id}:side-opening`) % 3;
  const actions = [
    `${pet.name}${profile.focus}，忽然盯住了现场最不起眼的那一处。`,
    `${pet.name}${profile.signal}，没等两个人交换意见便先动了起来。`,
    `${pet.name}${profile.move}，又在你鞋边停下，像是特意确认你已经看见。`
  ];
  return `${setting}${incident ? `${incident}。` : ''}${actions[index]}`;
}

function sideEvent(pet, row) {
  const [id, stage, contextType, contextValue, triggerType, behavior, threshold, probability, title, cause] = row;
  const details = sideStoryDetails[pet.key]?.[id] || generatedSideStoryDetails(pet, row);
  const [goal, turn, action, result, hook, bridge] = details;
  return {
    id, stage, contextType, contextValue, triggerType, behavior, threshold, probability, title, cause,
    event:{
      title, summary:cause, scene:sideStoryScene(pet, row, cause),
      goal, turn, action, result, hook, bridge
    }
  };
}

