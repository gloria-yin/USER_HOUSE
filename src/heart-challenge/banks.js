export function keywordList(value) {
  return String(value || '').split(/[,，、;；\n]+/).map(x => x.trim()).filter(Boolean);
}

export function bankCatalog(customBanks = []) {
  return [...Object.values(HEART_BANKS), ...customBanks];
}

export function createCustomBank(input, id) {
  const name = String(input.name || '').trim();
  if (!name || name.length > 60) throw new Error('牌库名称需要 1—60 个字符。');
  if (!/^custom_[a-zA-Z0-9_]+$/.test(id)) throw new Error('自定义牌库标识无效。');
  const result = [];
  for (const [type, field] of [['T', 'truth'], ['D', 'dare']]) {
    const questions = String(input[field] || '').split(/\r?\n/).map(line => line.trim()).filter(Boolean);
    const label = type === 'T' ? '真心话' : '大冒险';
    if (questions.length < 2 || questions.length > 200) throw new Error(`${label}需要 2—200 道题，每行一道。`);
    if (new Set(questions).size !== questions.length) throw new Error(`${label}中有重复题目，请合并后保存。`);
    if (questions.some(question => question.length > 500 || /[|<>\u0000-\u0008]/.test(question))) throw new Error(`${label}每题最多 500 字，使用纯文本，题目中请使用中文标点代替 |、<、>。`);
    questions.forEach((question, index) => result.push({ id:`${id}-${type}-${index + 1}`, type, tag:label, question, adult:input.adult === true, weight:1 }));
  }
  return { id, name, adult:input.adult === true, custom:true, cards:result };
}

export function sourceCards(config, customBanks = []) {
  if (config.source === 'random') return [];
  const bank = bankCatalog(customBanks).find(bank => bank.id === (config.bank || 'regular'));
  if (!bank) throw new Error('所选牌库已不存在，请重新选择牌库。');
  if ((bank.id === 'intimate' || bank.adult) && !config.nsfw) throw new Error('这套牌库需要开启成人内容。');
  const exclusions = keywordList(config.excludes);
  return bank.cards.filter(card => !exclusions.some(word => card.question.includes(word)));
}
