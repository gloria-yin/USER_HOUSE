const tags = ['轻松', '反差', '默契', '意外', '试探'];
function cards(text, deck, type) {
  return text.trim().split('\n').map((question, i) => ({
    id:`${deck}-${type}-${String(i + 1).padStart(2, '0')}`, type,
    tag:deck === 'intimate' ? ['暧昧', '温柔', '试探', '默契', '心意'][i % 5] : tags[i % 5],
    question, adult:deck === 'intimate', weight:1,
  }));
}

